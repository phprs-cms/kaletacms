<?php
/**
 * Schema reference (3.42, audit Q20): php tools/schema-doc.php [--check]
 *
 * Writes docs/schema.md from system/sql/schema.sql (tables, columns, types, the comments next to them) and
 * system/sql/names.php (the English name of each table and of the columns it maps), so the meaning of `idc`, `tema` or
 * `ido` is one click away for a contributor who reads no Czech. With --check it only says whether the file is current
 * (exit 1 when not); the unit test 3660 does the same. Run it after every change of schema.sql.
 */

declare(strict_types=1);

/**
 * The Markdown of the schema reference.
 *
 * @param array<string, array{0: string, 1: array<string, string>}> $names system/sql/names.php
 */
function kaleta_schema_doc(string $sql, array $names): string
{
    $lines = preg_split('/\R/', $sql) ?: [];
    $tables = [];
    $comment = [];
    $current = null;
    foreach ($lines as $line) {
        $trim = trim($line);
        if ($current === null) {
            if (preg_match('/^CREATE TABLE (?:IF NOT EXISTS )?`?ka_([a-z0-9_]+)`?\s*\(/i', $trim, $m)) {
                $current = ['name' => $m[1], 'about' => implode(' ', $comment), 'columns' => [], 'keys' => []];
                $comment = [];
            } elseif (str_starts_with($trim, '--')) {
                $text = trim(substr($trim, 2));
                $comment = preg_match('/^-{3,}$/', $text) === 1 ? [] : ($text === '' ? $comment : [...$comment, $text]);
            } elseif ($trim !== '') {
                $comment = [];
            }
            continue;
        }
        if (str_starts_with($trim, ')')) {
            $tables[] = $current;
            $current = null;
            continue;
        }
        [$definition, $note] = array_pad(explode('--', $trim, 2), 2, '');
        $definition = rtrim(trim($definition), ',');
        if ($definition === '') {
            continue;
        }
        if (preg_match('/^(PRIMARY KEY|UNIQUE KEY|KEY|INDEX|FULLTEXT|CONSTRAINT|FOREIGN KEY)\b/i', $definition)) {
            $current['keys'][] = preg_replace('/\s+/', ' ', $definition);
            continue;
        }
        if (preg_match('/^`?([a-z0-9_]+)`?\s+(.+)$/i', $definition, $m)) {
            $type = preg_replace('/\s+/', ' ', $m[2]);
            $type = preg_replace('/ (CHARACTER SET \w+|COLLATE \w+)/i', '', (string) $type);
            $current['columns'][] = ['name' => $m[1], 'type' => trim((string) $type), 'note' => trim($note)];
        }
    }

    $cell = fn (string $text): string => str_replace(['|', "\n"], ['\\|', ' '], $text);
    $out = [
        '# Database schema',
        '',
        '<!-- Generated by tools/schema-doc.php from system/sql/schema.sql and system/sql/names.php – do not edit by hand. -->',
        '',
        'Every table of a new installation, with its columns and the comments of `system/sql/schema.sql`. The prefix `ka_` is the',
        'one from `config.php`. Older tables and columns have Czech names (they are never renamed); the **English** column gives the',
        'name from the rename map `system/sql/names.php` (`Core\\Names`) – code may write `{news}` as well as `{novinky}` – and,',
        'for the mapped columns, their English meaning. Older identifiers: `idc` = news item, `tema`/`idt` = category, `ido` =',
        'media item, `idu` = user.',
        '',
        count($tables) . ' tables:',
        '',
    ];
    $index = [];
    foreach ($tables as $t) {
        $english = $names[$t['name']][0] ?? '';
        $index[] = '[`ka_' . $t['name'] . '`](#ka_' . $t['name'] . ')' . ($english !== '' && $english !== $t['name'] ? ' (' . $english . ')' : '');
    }
    $out[] = implode(' · ', $index);
    foreach ($tables as $t) {
        $english = $names[$t['name']][0] ?? '';
        $columns = $names[$t['name']][1] ?? [];
        $out[] = '';
        $out[] = '## ka_' . $t['name'];
        $out[] = '';
        if ($english !== '' && $english !== $t['name']) {
            $out[] = 'English name: `' . $english . '`.' . ($t['about'] !== '' ? ' ' . $t['about'] : '');
        } elseif ($t['about'] !== '') {
            $out[] = $t['about'];
        }
        if ($english !== '' || $t['about'] !== '') {
            $out[] = '';
        }
        $out[] = '| Column | English | Type | Note |';
        $out[] = '|---|---|---|---|';
        foreach ($t['columns'] as $c) {
            $out[] = '| `' . $c['name'] . '` | ' . (isset($columns[$c['name']]) ? '`' . $columns[$c['name']] . '`' : '') . ' | ' . $cell($c['type']) . ' | ' . $cell($c['note']) . ' |';
        }
        if ($t['keys'] !== []) {
            $out[] = '';
            $out[] = 'Keys: ' . implode('; ', array_map(fn (string $k): string => '`' . $k . '`', $t['keys'])) . '.';
        }
    }

    return implode("\n", $out) . "\n";
}

if (realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === __FILE__) {
    $root = dirname(__DIR__);
    $doc = kaleta_schema_doc((string) file_get_contents($root . '/system/sql/schema.sql'), require $root . '/system/sql/names.php');
    $target = $root . '/docs/schema.md';
    if (in_array('--check', $argv, true)) {
        $current = is_file($target) && file_get_contents($target) === $doc;
        echo $current ? "docs/schema.md is current.\n" : "docs/schema.md is out of date – run php tools/schema-doc.php\n";
        exit($current ? 0 : 1);
    }
    file_put_contents($target, $doc);
    echo 'docs/schema.md written (' . substr_count($doc, "\n## ") . " tables).\n";
}
